// Printable proof-of-service report for a storm (keep for slip-and-fall claims).
import { requireOwner } from "@/server/auth";
import { notFound } from "next/navigation";
import { businessId } from "@/server/db";
import { stormReport } from "@/server/stormReport";

export const metadata = { title: "Storm report" };

export default async function StormReport({ params }: PageProps<"/snow/[id]/report">) {
  await requireOwner();
  const { id } = await params;
  const data = await stormReport(await businessId(), id).catch(() => null);
  if (!data) notFound();
  const { ev, rows } = data;
  return (
    <div className="bg-white p-4 text-sm">
      <div className="no-print mb-4 flex gap-2">
        <a href="javascript:print()" className="rounded-full bg-navy px-4 py-2 font-semibold text-white">Print / save PDF</a>
        <a href={`/api/export/storm/${id}`} className="rounded-full border-2 border-line px-4 py-2 font-semibold">Download CSV</a>
      </div>
      <h1 className="font-display text-2xl font-bold">Proof of service · {ev.name}</h1>
      <p className="text-ink-soft">{ev.season.name} · forecast {ev.forecastCm ?? "?"} cm · measured {ev.measuredCm ?? "?"} cm · {ev.pushCount} push{ev.pushCount > 1 ? "es" : ""} · status {ev.status.toLowerCase()}</p>
      <table className="mt-4 w-full border-collapse">
        <thead><tr className="border-b-2 border-navy text-left text-xs uppercase">
          <th className="py-1 pr-2">#</th><th className="pr-2">Address</th><th className="pr-2">Push</th><th className="pr-2">Result</th><th className="pr-2">Arrived</th><th className="pr-2">Done / skipped</th><th className="pr-2">Depth</th><th className="pr-2">Melt</th><th>GPS</th>
        </tr></thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={r.id} className="break-inside-avoid border-b border-line align-top">
              <td className="py-1.5 pr-2">{i + 1}</td>
              <td className="pr-2"><b>{r.address}</b><div className="text-xs text-ink-soft">{r.client} · {r.community}</div>
                {r.photos.length > 0 && (
                  <div className="mt-1 flex flex-wrap gap-1">
                    {/* eslint-disable-next-line @next/next/no-img-element -- private media, owner session */}
                    {r.photos.slice(0, 4).map((p) => <img key={p.id} src={`/api/media/${p.id}/sm`} alt={p.kind} className="h-14 w-20 rounded object-cover" />)}
                  </div>
                )}
              </td>
              <td className="pr-2">{r.push}</td>
              <td className="pr-2">{r.state.toLowerCase()}{r.skipReason && <div className="text-xs">{r.skipReason.toLowerCase().replaceAll("_", " ")}{r.skipNote && `: ${r.skipNote}`}</div>}</td>
              <td className="pr-2">{r.arrived}</td>
              <td className="pr-2">{r.completed || r.skipped}</td>
              <td className="pr-2">{r.depthCm != null ? `${r.depthCm} cm` : ""}</td>
              <td className="pr-2">{r.iceMelt}</td>
              <td>{r.gps && <a className="text-blue" href={`https://www.google.com/maps/search/?api=1&query=${r.gps}`}>{r.gps}</a>}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="mt-4 text-xs text-ink-soft">Times in Calgary time. GPS is the crew phone&apos;s location when the visit was marked done. Generated by etc. CRM.</p>
    </div>
  );
}
